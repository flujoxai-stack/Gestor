create table if not exists public.companies (
    id text primary key,
    owner_id uuid not null references auth.users(id) on delete cascade,
    name text not null,
    status text not null default 'active' check (status in ('active', 'inactive')),
    projected_amount numeric not null default 0,
    projected_notes text default '',
    activity_log text not null default '[]',
    created_at text not null
);

create table if not exists public.projects (
    id text primary key,
    owner_id uuid not null references auth.users(id) on delete cascade,
    name text not null,
    status text default 'lead',
    start_date text,
    end_date text,
    warranty_start text,
    warranty_end text,
    pipeline_order integer default 0,
    company_id text references public.companies(id) on delete set null
);

create table if not exists public.tasks (
    id text primary key,
    owner_id uuid not null references auth.users(id) on delete cascade,
    project_id text references public.projects(id) on delete cascade,
    title text not null,
    description text,
    status text default 'todo',
    priority text default 'Media',
    due_date text
);

create table if not exists public.finances (
    id text primary key,
    owner_id uuid not null references auth.users(id) on delete cascade,
    concept text not null,
    type text not null check (type in ('income', 'expense')),
    amount numeric not null,
    date text not null,
    project_id text
);

create table if not exists public.activities (
    id text primary key,
    owner_id uuid not null references auth.users(id) on delete cascade,
    title text not null,
    "desc" text,
    date text not null
);

create table if not exists public.notes (
    id text primary key,
    owner_id uuid not null references auth.users(id) on delete cascade,
    title text not null,
    content text,
    folder text default 'General',
    color text default '#ffffff',
    created_at text not null
);

create table if not exists public.note_folders (
    id bigint generated by default as identity primary key,
    owner_id uuid not null references auth.users(id) on delete cascade,
    name text not null,
    unique (owner_id, name)
);

create table if not exists public.settings (
    owner_id uuid not null references auth.users(id) on delete cascade,
    key text not null,
    value text,
    primary key (owner_id, key)
);

create table if not exists public.integrations (
    id text primary key,
    owner_id uuid not null references auth.users(id) on delete cascade,
    name text not null,
    type text not null default 'webhook',
    enabled boolean not null default true,
    config text not null default '{}',
    created_at text not null,
    updated_at text not null
);

create table if not exists public.integration_events (
    id text primary key,
    owner_id uuid not null references auth.users(id) on delete cascade,
    integration_id text references public.integrations(id) on delete cascade,
    event_type text not null,
    payload text,
    status text not null default 'sent',
    response text,
    created_at text not null
);

create table if not exists public.business_notifications (
    id text primary key,
    owner_id uuid not null references auth.users(id) on delete cascade,
    source text not null default 'gmail',
    label text not null default 'negocios',
    from_name text,
    from_email text,
    subject text not null default '',
    snippet text,
    body text,
    message_id text,
    thread_id text,
    url text,
    metadata text not null default '{}',
    received_at text not null,
    is_read boolean not null default false,
    notes text,
    created_at text not null,
    updated_at text not null
);

