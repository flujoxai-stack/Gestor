-- Seguridad (SEC-02): el backend (server.js) habla con Supabase usando la
-- SUPABASE_SERVICE_ROLE_KEY, que ignora RLS por diseño. El navegador nunca
-- debe tener una vía directa a estas tablas, así que NO se le concede nada
-- al rol "anon" y se activa RLS en todas las tablas. Además de RLS, cada
-- ruta de server.js filtra explícitamente por owner_id -- esa es la
-- protección real (multi-cuenta), RLS es una segunda capa. Ver también
-- supabase/migrations/001_enable_rls.sql, 002_add_companies.sql y
-- 003_multi_tenant.sql si estás aplicando esto sobre un proyecto que ya
-- tenía las tablas creadas con el esquema anterior (de un solo usuario).
